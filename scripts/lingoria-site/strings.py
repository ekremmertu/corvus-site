def extra(lang):
    """Deyim kartları (#idioms, erişilebilir düğmeler) + hero oyuncağının verisi."""
    import html, json
    hint = (TR if lang == "tr" else EN)["flip_hint"]
    cards = []
    for i, (en, tr, gloss) in enumerate(IDIOMS[:12]):
        mean = tr if lang == "tr" else gloss
        cards.append(
            f'<button type="button" class="icard" aria-pressed="false" data-reveal>'
            f'<span class="f"><i>{html.escape(en)}</i><small>{html.escape(hint)}</small></span>'
            f'<span class="b">{html.escape(mean)}</span></button>'
        )
    data = [{"en": en, "m": tr if lang == "tr" else gloss} for en, tr, gloss in IDIOMS]
    return {"idiom_cards": "\n    ".join(cards), "idioms_json": html.escape(json.dumps(data, ensure_ascii=False))}
